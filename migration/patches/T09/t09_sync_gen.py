#!/usr/bin/env python3
"""T09: sync the takeover-attributable generated changes into the repository.

`make api` regenerates the whole api/gen/go tree, which also reproduces the
pre-existing toolchain-header drift HEAD carries (24 modified files plus 8 empty
*.pb.validate.go shells that do not exist in the committed tree). Phase C allows
only the takeover change, and the accepted T08 precedent is: commit the import
line, leave the inherited drift alone.

So each of the 8 redact-consumer files is rebuilt as
    HEAD content + exactly the hunks whose +/- lines mention the redact import
and nothing else. Afterwards `git diff -- api/gen/go` must show 8 files and every
changed line must be an import of
    go-wind-admin/pkg/localdeps/go-wind-toolkit/protoc-gen-go-redact/redact/v1
"""
import difflib
import os
import subprocess
import sys

D = "/home/ubuntu/tx7do-pilot-run/T09"
REPO = "/home/ubuntu/Workspace/ani-governance"
OLD = "github.com/tx7do/go-wind-toolkit/protoc-gen-go-redact/redact/v1"
NEW = "go-wind-admin/pkg/localdeps/go-wind-toolkit/protoc-gen-go-redact/redact/v1"

FILES = [
    "admin/service/v1/i_user.pb.go",
    "admin/service/v1/i_user.pb.redact.go",
    "authentication/service/v1/ani_auth.pb.go",
    "authentication/service/v1/ani_auth.pb.redact.go",
    "authentication/service/v1/authentication.pb.go",
    "authentication/service/v1/authentication.pb.redact.go",
    "identity/service/v1/user.pb.go",
    "identity/service/v1/user.pb.redact.go",
]


def run(*cmd, cwd=REPO, ok=False):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if p.returncode != 0 and not ok:
        sys.exit(f"FAIL {cmd}: {p.stdout}{p.stderr}")
    return p.stdout


def split_hunks(diff):
    """Return the file header plus a list of hunks (each a list of lines)."""
    head, hunks, cur = [], [], None
    for line in diff.splitlines(keepends=True):
        if line.startswith("@@"):
            cur = [line]
            hunks.append(cur)
        elif cur is not None and line[:1] in ("+", "-", " ", "\\"):
            cur.append(line)
        else:
            if cur is None:
                head.append(line)
    return head, hunks


def main():
    run("git", "checkout", "--", "api/gen/go")
    # The control (T09-ctl-trees.diff) proves the takeover adds no file under
    # api/gen/go: 8 "differ" lines and zero "Only in". So anything untracked here
    # after a full `make api` is the class-2 noise scripts/post-generate-clean.sh
    # already documents (empty protoc-gen-validate shells), kept out of the repo to
    # preserve its existing file set. Assert that before removing anything.
    with open(f"{D}/T09-ctl-trees.diff") as fh:
        ctl = fh.read()
    added = [l for l in ctl.splitlines() if l.startswith("Only in")]
    if added:
        sys.exit(f"FAIL: the takeover adds files under api/gen/go, review them:\n{added}")
    differed = len([l for l in ctl.splitlines() if l.startswith("Files ")])
    if differed != len(FILES):
        sys.exit(f"FAIL: control reports {differed} differing files, expected {len(FILES)}")
    untracked = run("git", "ls-files", "--others", "--exclude-standard", "api/gen/go").split()
    for f in untracked:
        if not f.endswith(".pb.validate.go"):
            sys.exit(f"FAIL: unexpected untracked generated file {f}")
        with open(f"{REPO}/{f}") as fh:
            body = fh.read()
        if "Code generated by protoc-gen-validate" not in body:
            sys.exit(f"FAIL: {f} is not generator output")
        os.remove(f"{REPO}/{f}")
        print(f"removed regeneration shell, not present in HEAD: {f}")

    kept_lines = 0
    for rel in FILES:
        with open(f"{D}/head/api/gen/go/{rel}") as fh:
            a = fh.readlines()
        with open(f"{D}/post/api/gen/go/{rel}") as fh:
            b = fh.readlines()
        diff = "".join(difflib.unified_diff(a, b, fromfile=f"a/api/gen/go/{rel}",
                                            tofile=f"b/api/gen/go/{rel}", n=3))
        _, hunks = split_hunks(diff)
        kept, dropped = [], []
        for h in hunks:
            changed = [l for l in h[1:] if l[:1] in "+-" and not l.startswith(("+++", "---"))]
            (kept if changed and all(OLD in l or NEW in l for l in changed) else dropped).append(h)
        if not kept:
            sys.exit(f"FAIL: {rel} carries no redact-import hunk")
        patch = "".join([f"--- a/api/gen/go/{rel}\n", f"+++ b/api/gen/go/{rel}\n"] +
                        [l for h in kept for l in h])
        subprocess.run(["git", "apply", "-p1"], cwd=REPO, input=patch,
                       capture_output=True, text=True, check=True)
        n = sum(len([l for l in h[1:] if l[:1] in "+-" and not l.startswith(("+++", "---"))])
                for h in kept)
        kept_lines += n
        print(f"{rel}: applied {len(kept)} takeover hunk(s) ({n} +/- lines), "
              f"excluded {len(dropped)} pre-existing-drift hunk(s)")

    print(f"\ntotal takeover +/- lines across 8 files: {kept_lines}")

    print("\n=== verify 1: every changed working-tree line is a redact import ===")
    d = run("git", "diff", "-U0", "--", "api/gen/go")
    offenders = [l for l in d.splitlines()
                 if l[:1] in "+-" and not l.startswith(("+++", "---"))
                 and OLD not in l and NEW not in l]
    print("offending lines:", offenders or "none")
    print("files changed:", len([l for l in d.splitlines() if l.startswith("diff --git")]))

    print("\n=== verify 2: result equals a byte-for-byte regeneration, modulo the excluded drift ===")
    for rel in FILES:
        with open(f"{REPO}/api/gen/go/{rel}") as fh:
            now = fh.read()
        with open(f"{D}/post/api/gen/go/{rel}") as fh:
            regen = fh.read()
        if now == regen:
            print(f"{rel}: identical to the post-change regeneration")
        else:
            _, hk = split_hunks("".join(difflib.unified_diff(now.splitlines(True),
                                                         regen.splitlines(True))))
            only_header = all(
                all("protoc-gen-go v1.36." in l for l in h[1:] if l[:1] in "+-")
                for h in hk)
            print(f"{rel}: differs from regeneration in {len(hk)} hunk(s), "
                  f"toolchain-header-only={only_header}")
    return 0 if not offenders else 1


sys.exit(main())
